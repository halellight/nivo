#!/usr/bin/env python3
"""Build src/data/map-data.ts from the HDX/OCHA Nigeria admin-2 boundaries.

    pip install shapely numpy pillow
    python scripts/build_map_data.py data/nga_admin2.geojson src/data/map-data.ts

Everything is projected into one 736 x 654 space (the Figma map frame) and simplified together with
shapely.coverage_simplify, so LGA edges, state borders and the country outline always line up.
"""
import base64, io, json, sys
import numpy as np
from PIL import Image, ImageDraw
from shapely import coverage_simplify, transform, unary_union
from shapely.geometry import Polygon, shape

SRC = sys.argv[1] if len(sys.argv) > 1 else "data/nga_admin2.geojson"
OUT = sys.argv[2] if len(sys.argv) > 2 else "src/data/map-data.ts"
W, H, TOL = 736, 654, 0.22
LON0, LON1, LAT0, LAT1 = 2.66853, 14.67882, 4.27301, 13.89442  # Nigeria's bounding box
AX, AY = 735.28 / (LON1 - LON0), 653.3 / (LAT1 - LAT0)

def project(c):  # lon/lat -> map units
    return np.c_[0.35 + (c[:, 0] - LON0) * AX, 0.35 + (LAT1 - c[:, 1]) * AY]

def state_key(name):  # "Lagos" -> "Lagos State"
    return "Federal Capital Territory" if name.startswith("Federal Capital") else name + " State"

def polys(g):
    return [g] if g.geom_type == "Polygon" else [p for p in g.geoms if p.geom_type == "Polygon"]

def path(ps):
    out = []
    for p in ps:
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)
            if len(c) >= 4:
                out.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in c[:-1]) + "Z")
    return "".join(out)

feats = json.load(open(SRC))["features"]
geoms = [transform(shape(f["geometry"]), project) for f in feats]
geoms = list(coverage_simplify(np.array(geoms, dtype=object), TOL))

LG, parts = {}, {}
for f, g in zip(feats, geoms):
    if g.is_empty:
        continue
    k = state_key(f["properties"]["adm1_name"])
    LG.setdefault(k, []).append([f["properties"]["adm2_name"], path(polys(g))])
    parts.setdefault(k, []).append(g)
LG = {k: sorted(v, key=lambda r: r[0]) for k, v in sorted(LG.items())}
KEYS = list(LG)
states = {k: unary_union(parts[k]) for k in KEYS}
BB = {k: [round(v, 1) for v in states[k].bounds] for k in KEYS}
SO = {k: path(polys(states[k])) for k in KEYS}                       # per-state outline
country = unary_union(list(states.values()))
OUTLINE = path([Polygon(p.exterior) for p in polys(country)])         # Nigeria outline
BORDERS = path([p for k in KEYS for p in polys(states[k])])           # all state borders

M = 2  # mask scale: 2 -> 1472x1308. 3 is sharper but 2.25x heavier to redraw on phones.
img = Image.new("L", (W * M, H * M), 0)   # grayscale: pixel value = 1-based index into KEYS
d = ImageDraw.Draw(img)
for i, k in enumerate(KEYS, 1):
    for p in polys(states[k]):
        d.polygon([(x * M, y * M) for x, y in p.exterior.coords], fill=i, outline=i)
        for r in p.interiors:
            d.polygon([(x * M, y * M) for x, y in r.coords], fill=0)
buf = io.BytesIO()
img.save(buf, "PNG", optimize=True)
MASK = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()

j = lambda v: json.dumps(v, ensure_ascii=False, separators=(",", ":"))
open(OUT, "w").write(f"""/* GENERATED by scripts/build_map_data.py - do not edit by hand. */
export const OUTLINE = {j(OUTLINE)};
export const BORDERS = {j(BORDERS)};
/** state hit-mask: red channel = 1-based index into KEYS */
export const MASK = {j(MASK)};
export const KEYS: string[] = {j(KEYS)};
export const BB: Record<string, [number, number, number, number]> = {j(BB)};
export const SO: Record<string, string> = {j(SO)};
export const LG: Record<string, [string, string][]> = {j(LG)};
""")
print(f"wrote {OUT}: {len(KEYS)} states, {sum(map(len, LG.values()))} LGAs")
